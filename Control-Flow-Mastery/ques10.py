# Check Divisibility by Both 3 and 5

# Write your code here
n = int(input())
m = int(input())

if n % 3 == 0 and n % 5 == 0:
    print("Divisible by both 3 and 5")
else:
    print("Not divisible by both 3 and 5")

if m % 3 == 0 and m % 5 == 0:
    print("Divisible by both 3 and 5")
else:
    print("Not divisible by both 3 and 5")