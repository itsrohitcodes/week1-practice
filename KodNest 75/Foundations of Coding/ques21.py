# Min Cost Climbing Stairs

def min_cost_climbing_stairs(cost):
    # Implement the function here ...
    n = len(cost)
    dp = [0] * n
    dp[0] = cost[0]
    dp[1] = cost[1]

    for i in range(2, n):
        dp[i] = cost[i] + min(dp[i-1], dp[i-2])

    return min(dp[n-1], dp[n-2])


